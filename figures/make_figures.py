# ------------------------------------------------------------------ single-Gaussian model
def Ein(a):                       # Eq. (17): Ein(a) = gamma_E + ln a + E1(a)
    return EULER + np.log(a) + exp1(a)

def I1(a, nmax=200):              # Eq. (19)
    n = np.arange(1, nmax + 1)
    return np.sum((-1.0) ** (n + 1) * np.exp(n * np.log(a) - gammaln(n + 1)) / n**2)

def F(Q, a, nmax=250):            # Eq. (16)
    n = np.arange(1, nmax + 1)
    return np.sum((-1.0) ** (n + 1) * np.exp(n * np.log(a) - gammaln(n + 1)) / n * np.exp(-Q / n))

def params_A(sqrts, sqrts_ref=7000.0, lam_ref=10.0, nu_ref=4.0, Delta=0.0808, alphaP=0.25):
    L = 2 * np.log(sqrts / sqrts_ref)                    # Eq. (7)
    H = 4 * np.pi * lam_ref * nu_ref * np.exp(Delta * L)
    lam = lam_ref + alphaP * L
    return H, lam, H / (4 * np.pi * lam)                 # Eq. (11): nu = H/(4 pi lambda)

def calibrate_B(stot_mb=110.6, r=0.281):                 # Eq. (21) and Eq. (18)
    a = brentq(lambda x: 1 - Ein(2 * x) / (2 * Ein(x)) - r, 1e-3, 50)
    lam = (stot_mb / GEV2_TO_MB) / (8 * np.pi * Ein(a))
    return lam, 2 * a

def dsdt(t, lam, a):              # Eq. (19), mb/GeV^2
    return 4 * np.pi * lam**2 * F(lam * t, a) ** 2 * GEV2_TO_MB

def dsdt_born(t, H, lam):         # Eq. (8)
    return H**2 / (16 * np.pi) * np.exp(-2 * lam * t) * GEV2_TO_MB

def bin_average(f, lo, hi, n=24):
    x, w = leggauss(n)
    t = 0.5 * (hi - lo) * x + 0.5 * (hi + lo)
    return 0.5 * np.sum(w * np.array([f(tt) for tt in t]))

# ------------------------------------------------------------------ complex / two-component models (Sec. VII)
DELTA, ALPHAP = 0.0808, 0.25
TAU = np.tan(np.pi * DELTA / 2)
xb, wb = leggauss(3000)
BMAX = 60.0
BB = 0.5 * BMAX * (xb + 1)
WB = 0.5 * BMAX * wb

def comps(H, lam):                                       # Eq. (22): H_c, lambda_c
    return [(H * (1 - 1j * TAU), lam - 1j * np.pi * ALPHAP / 2)]

def dsdt_b(t, cs):                                       # numerical Hankel transform of Eq. (10)
    t = np.atleast_1d(t)
    Om = sum(Hc / (4 * np.pi * lc) * np.exp(-BB**2 / (4 * lc)) for Hc, lc in cs)
    G = 1 - np.exp(-Om / 2)
    A = 4 * np.pi * (j0(np.sqrt(t)[:, None] * BB[None, :]) * (BB * G * WB)[None, :]).sum(axis=1)
    return np.abs(A) ** 2 / (16 * np.pi) * GEV2_TO_MB

def binavg_b(cs, n=8):
    x, w = leggauss(n)
    T = 0.5 * (HI - LO)[:, None] * x[None, :] + 0.5 * (HI + LO)[:, None]
    return (dsdt_b(T.ravel(), cs).reshape(T.shape) * 0.5 * w[None, :]).sum(axis=1)

