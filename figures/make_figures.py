def energy_scan():
    rs = np.geomspace(1000, 1e5, 80)
    out = {k: [] for k in ["st", "se", "si", "sb", "sbel", "rat", "B0", "B0b"]}
    for x in rs:
        H, l, nu = params_A(x); a = nu / 2
        st, si = 8 * np.pi * l * Ein(a), 4 * np.pi * l * Ein(2 * a)          # Eq. (18)
        out["st"].append(st * GEV2_TO_MB); out["si"].append(si * GEV2_TO_MB); out["se"].append((st - si) * GEV2_TO_MB)
        out["sb"].append(H * GEV2_TO_MB); out["sbel"].append(H**2 / (32 * np.pi * l) * GEV2_TO_MB)
        out["rat"].append((st - si) / st); out["B0"].append(2 * l * I1(a) / Ein(a)); out["B0b"].append(2 * l)
    return rs, {k: np.array(v) for k, v in out.items()}

